//============================================================================
//! CONTACT MODEL
//============================================================================

class ContactModel {
  //============================================================================
  //! FIELDS
  //============================================================================

  final String id;

  final String name;

  final String? avatarUrl;

  final bool isOnline;

  //============================================================================
  //! CONSTRUCTOR
  //============================================================================

  const ContactModel({
    required this.id,
    required this.name,
    this.avatarUrl,
    this.isOnline = false,
  });
}
